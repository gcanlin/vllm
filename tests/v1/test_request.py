def test_request_token_lists_are_not_gc_tracked():
    """Token-id and block-hash lists stay out of the cyclic GC as they grow."""
    engine_request = EngineCoreRequest(
        request_id="request-1",
        prompt_token_ids=list(range(1000)),
        mm_features=None,
        sampling_params=SamplingParams(max_tokens=8),
        pooling_params=None,
        arrival_time=0.0,
        lora_request=None,
        cache_salt=None,
        data_parallel_rank=None,
    )
    request = Request.from_engine_core_request(
        engine_request, block_hasher=lambda r: [b"h" * 32]
    )

    request.append_output_token_ids([1000, 1001])
    request.append_output_token_ids(1002)

    assert list(request.all_token_ids[-3:]) == [1000, 1001, 1002]
    assert request.block_hashes
    for values in (
        request.prompt_token_ids,
        request._all_token_ids,
        request.block_hashes,
    ):
        assert not gc.is_tracked(values)
